#!/usr/bin/env bash
# Generates .env with strong random secrets. Run once on the server.
set -euo pipefail
cd "$(dirname "$0")/.."

if [ -f .env ]; then
  echo ".env already exists — delete it first if you really want new secrets." >&2
  exit 1
fi

rand() { head -c 48 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c "${1:-32}"; }

read -rp "Public host or IP users will open (e.g. 100.83.84.37): " HOST
read -rp "Admin email: " ADMIN_EMAIL
read -rp "DeepSeek API key (leave empty to disable AI): " DEEPSEEK_KEY

ORTHANC_USER=radkit
ORTHANC_PASSWORD=$(rand 32)
ORTHANC_BASIC_B64=$(printf '%s:%s' "$ORTHANC_USER" "$ORTHANC_PASSWORD" | base64 | tr -d '\n')
ADMIN_PASSWORD=$(rand 16)

cat > .env <<EOF
# ---- generated by scripts/init.sh on $(date -u +%F) ----
APP_PORT=80
VIEWER_PORT=8081
PUBLIC_APP_URL=http://${HOST}
PUBLIC_VIEWER_URL=http://${HOST}:8081
COOKIE_SECURE=false

POSTGRES_DB=radkit
POSTGRES_USER=radkit
POSTGRES_PASSWORD=$(rand 32)

ORTHANC_USER=${ORTHANC_USER}
ORTHANC_PASSWORD=${ORTHANC_PASSWORD}
ORTHANC_BASIC_B64=${ORTHANC_BASIC_B64}

JWT_SECRET=$(rand 64)
SHARE_SECRET=$(rand 64)

ADMIN_EMAIL=${ADMIN_EMAIL}
ADMIN_PASSWORD=${ADMIN_PASSWORD}

DEEPSEEK_API_KEY=${DEEPSEEK_KEY}
DEEPSEEK_BASE_URL=https://api.deepseek.com
DEEPSEEK_MODEL=deepseek-flash
EOF
chmod 600 .env

echo
echo "  .env written."
echo "  Admin login: ${ADMIN_EMAIL}"
echo "  Admin password: ${ADMIN_PASSWORD}   (change it after first login)"
echo
echo "  Next: docker compose up -d --build"
